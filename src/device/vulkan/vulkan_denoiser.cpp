uint32_t VulkanDenoiser::Impl::memoryType(uint32_t bits, VkMemoryPropertyFlags flags) const
{
    for (uint32_t i = 0; i < memory.memoryTypeCount; ++i)
        if ((bits & (1u << i)) && (memory.memoryTypes[i].propertyFlags & flags) == flags) return i;
    return ~0u;
}

void VulkanDenoiser::Impl::createBuffer(VkDeviceSize size, Memory kind, Buffer* buffer)
{
    *buffer = {};
    VkBufferCreateInfo info{VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO};
    info.size = std::max<VkDeviceSize>(16, size);
    info.usage = VK_BUFFER_USAGE_STORAGE_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_SRC_BIT |
                 VK_BUFFER_USAGE_TRANSFER_DST_BIT | VK_BUFFER_USAGE_SHADER_DEVICE_ADDRESS_BIT;
    CheckVk(vkCreateBuffer(d.device, &info, nullptr, &buffer->buffer), "vkCreateBuffer");
    VkMemoryRequirements requirements;
    vkGetBufferMemoryRequirements(d.device, buffer->buffer, &requirements);
    const VkMemoryPropertyFlags host = VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
    uint32_t type = ~0u;
    switch (kind) {
    case Memory::Device: type = memoryType(requirements.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT); break;
    case Memory::Readback:
        // The host reads it: cached memory when there is some.
        type = memoryType(requirements.memoryTypeBits, host | VK_MEMORY_PROPERTY_HOST_CACHED_BIT);
        [[fallthrough]];
    case Memory::Upload:
        if (type == ~0u) type = memoryType(requirements.memoryTypeBits, host);
        break;
    }
    VkMemoryAllocateFlagsInfo flags{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_FLAGS_INFO};
    flags.flags = VK_MEMORY_ALLOCATE_DEVICE_ADDRESS_BIT;
    VkMemoryAllocateInfo allocation{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    allocation.pNext = &flags;
    allocation.allocationSize = requirements.size;
    allocation.memoryTypeIndex = type;
    const VkResult allocated = type == ~0u ? VK_ERROR_OUT_OF_DEVICE_MEMORY
                                           : vkAllocateMemory(d.device, &allocation, nullptr, &buffer->memory);
    if (allocated != VK_SUCCESS) {
        vkDestroyBuffer(d.device, buffer->buffer, nullptr);
        *buffer = {};
        CheckVk(allocated, "vkAllocateMemory (the denoiser's images)");
    }
    vkBindBufferMemory(d.device, buffer->buffer, buffer->memory, 0);
    if (kind != Memory::Device) vkMapMemory(d.device, buffer->memory, 0, VK_WHOLE_SIZE, 0, &buffer->mapped);
    VkBufferDeviceAddressInfo address{VK_STRUCTURE_TYPE_BUFFER_DEVICE_ADDRESS_INFO};
    address.buffer = buffer->buffer;
    buffer->address = vkGetBufferDeviceAddress(d.device, &address);
    buffer->size = info.size;
}

void VulkanDenoiser::Impl::destroyBuffer(Buffer& buffer)
{
    if (buffer.buffer) vkDestroyBuffer(d.device, buffer.buffer, nullptr);
    if (buffer.memory) vkFreeMemory(d.device, buffer.memory, nullptr);
    buffer = {};
}

void VulkanDenoiser::Impl::reserve(Buffer& buffer, VkDeviceSize size, Memory kind)
{
    if (buffer.size >= size) return;
    destroyBuffer(buffer);
    createBuffer(size, kind, &buffer);
}

bool VulkanDenoiser::Impl::initialize(DenoiseDevice const& device, std::string* error)
{
    d = device;
    vkGetPhysicalDeviceMemoryProperties(d.physical, &memory);
    vkoidn::ContextCreateInfo info;
    info.instance = d.instance;
    info.physicalDevice = d.physical;
    info.device = d.device;
    info.getInstanceProcAddr = vkGetInstanceProcAddr;
    info.getDeviceProcAddr = vkGetDeviceProcAddr;
    info.enabledExtensions = d.extensions.data();
    info.enabledExtensionCount = uint32_t(d.extensions.size());
    info.pipelineCache = d.pipelineCache;
    if (const vkoidn::Result r = vkoidn::Context::create(info, context); r != vkoidn::Result::eSuccess) {
        *error = std::string("vk_oidn cannot run on this device (") + vkoidn::getResultString(r) + ")";
        return false;
    }
    VkCommandPoolCreateInfo poolInfo{VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO};
    poolInfo.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT | VK_COMMAND_POOL_CREATE_TRANSIENT_BIT;
    poolInfo.queueFamilyIndex = d.queueFamily;
    VkFenceCreateInfo fenceInfo{VK_STRUCTURE_TYPE_FENCE_CREATE_INFO};
    VkQueryPoolCreateInfo queryInfo{VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO};
    queryInfo.queryType = VK_QUERY_TYPE_TIMESTAMP;
    queryInfo.queryCount = 2;
    if (vkCreateCommandPool(d.device, &poolInfo, nullptr, &pool) != VK_SUCCESS ||
        vkCreateFence(d.device, &fenceInfo, nullptr, &fence) != VK_SUCCESS ||
        vkCreateQueryPool(d.device, &queryInfo, nullptr, &timestamps) != VK_SUCCESS) {
        *error = "cannot create the denoiser's command pool";
        return false;
    }
    VkPhysicalDeviceProperties properties;
    vkGetPhysicalDeviceProperties(d.physical, &properties);
    timestampPeriod = properties.limits.timestampPeriod;
    std::vector<char> spirv;
    if (!PassSpirv(&spirv, error)) return false;
    VkShaderModuleCreateInfo moduleInfo{VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO};
    moduleInfo.codeSize = spirv.size();
    moduleInfo.pCode = reinterpret_cast<const uint32_t*>(spirv.data());
    VkShaderModule module = VK_NULL_HANDLE;
    if (vkCreateShaderModule(d.device, &moduleInfo, nullptr, &module) != VK_SUCCESS) {
        *error = "cannot create the denoiser's shader module";
        return false;
    }
    VkPushConstantRange range{VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(PassParams)};
    VkPipelineLayoutCreateInfo layoutInfo{VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO};
    layoutInfo.pushConstantRangeCount = 1;
    layoutInfo.pPushConstantRanges = &range;
    VkResult result = vkCreatePipelineLayout(d.device, &layoutInfo, nullptr, &layout);
    if (result == VK_SUCCESS) {
        VkComputePipelineCreateInfo pipelineInfo{VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO};
        pipelineInfo.stage = {VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO};
        pipelineInfo.stage.stage = VK_SHADER_STAGE_COMPUTE_BIT;
        pipelineInfo.stage.module = module;
        pipelineInfo.stage.pName = "main";
        pipelineInfo.layout = layout;
        result = vkCreateComputePipelines(d.device, d.pipelineCache, 1, &pipelineInfo, nullptr, &pipeline);
    }
    vkDestroyShaderModule(d.device, module, nullptr);
    if (result != VK_SUCCESS) {
        *error = VulkanError("creating the denoiser's pipeline", result);
        return false;
    }
    return true;
}

void VulkanDenoiser::Impl::destroy()
{
    if (!d.device) return;
    color.reset();
    albedoFilter.reset();
    normalFilter.reset();
    haveFilters = false;
    for (Buffer* buffer : {&images, &upload, &readback, &scales}) destroyBuffer(*buffer);
    if (pipeline) vkDestroyPipeline(d.device, pipeline, nullptr);
    if (layout) vkDestroyPipelineLayout(d.device, layout, nullptr);
    if (fence) vkDestroyFence(d.device, fence, nullptr);
    if (pool) vkDestroyCommandPool(d.device, pool, nullptr);
    if (timestamps) vkDestroyQueryPool(d.device, timestamps, nullptr);
    timestamps = VK_NULL_HANDLE;
    pipeline = VK_NULL_HANDLE;
    layout = VK_NULL_HANDLE;
    fence = VK_NULL_HANDLE;
    pool = VK_NULL_HANDLE;
    context.reset();
    d.device = VK_NULL_HANDLE;
}

VkCommandBuffer VulkanDenoiser::Impl::begin()
{
    VkCommandBufferAllocateInfo info{VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
    info.commandPool = pool;
    info.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    info.commandBufferCount = 1;
    VkCommandBuffer commands = VK_NULL_HANDLE;
    CheckVk(vkAllocateCommandBuffers(d.device, &info, &commands), "vkAllocateCommandBuffers");
    VkCommandBufferBeginInfo beginInfo{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
    beginInfo.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(commands, &beginInfo);
    return commands;
}

void VulkanDenoiser::Impl::submit(VkCommandBuffer commands)
{
    vkEndCommandBuffer(commands);
    VkSubmitInfo info{VK_STRUCTURE_TYPE_SUBMIT_INFO};
    info.commandBufferCount = 1;
    info.pCommandBuffers = &commands;
    vkResetFences(d.device, 1, &fence);
    VkResult result;
    {
        std::lock_guard lock(*d.queueMutex);
        result = vkQueueSubmit(d.queue, 1, &info, fence);
    }
    if (result == VK_SUCCESS) result = vkWaitForFences(d.device, 1, &fence, VK_TRUE, UINT64_MAX);
    vkFreeCommandBuffers(d.device, pool, 1, &commands);
    CheckVk(result, "the denoise submission");
}

void VulkanDenoiser::Impl::ensureFilters(Key const& wanted)
{
    if (haveFilters && key == wanted) return;
    color.reset();
    albedoFilter.reset();
    normalFilter.reset();
    haveFilters = false;
    key = wanted;
    const bool prefilter = wanted.settings.prefilter && wanted.albedo;
    VkCommandBuffer commands = begin();
    try {
        // OIDN's colour filter: the guides it has, clean once prefiltered.
        vkoidn::DenoiserCreateInfo info;
        info.width = wanted.width;
        info.height = wanted.height;
        info.hdr = wanted.settings.hdr;
        info.albedo = wanted.albedo;
        info.normal = wanted.normal;
        info.cleanAux = prefilter;
        info.quality = ToVkOidn(wanted.settings.quality);
        Check(vkoidn::Denoiser::create(*context, commands, info, color), "creating the colour filter");
        if (prefilter) {
            // OIDN's albedo filter: LDR, sRGB transfer (srgb off); its normal
            // filter: LDR, linear transfer, on [0, 1] normals (kNormalToUnit).
            auto create = [&](const char* base, bool srgb, std::unique_ptr<vkoidn::Denoiser>* filter) {
                const std::string model = PrefilterModel(base, wanted.settings.quality);
                vkoidn::DenoiserCreateInfo guide;
                guide.width = wanted.width;
                guide.height = wanted.height;
                guide.hdr = false;
                guide.srgb = srgb;
                guide.quality = info.quality;
                guide.weights = prism::embedded::VkOidnPrefilterWeights(model.c_str(), &guide.weightsByteSize);
                if (!guide.weights) throw std::runtime_error("vk_oidn: the " + model + " weights are not in this build");
                Check(vkoidn::Denoiser::create(*context, commands, guide, *filter),
                      ("creating the " + model + " prefilter").c_str());
            };
            create("rt_alb", false, &albedoFilter);
            if (wanted.normal) create("rt_nrm", true, &normalFilter);
        }
    } catch (...) {
        vkEndCommandBuffer(commands);
        vkFreeCommandBuffers(d.device, pool, 1, &commands);
        throw;
    }
    // The weights' uploads, before any denoise.
    submit(commands);
    haveFilters = true;
    if (gpu::GpuVerbose()) {
        uint64_t bytes = color->getMemoryUsage();
        if (albedoFilter) bytes += albedoFilter->getMemoryUsage();
        if (normalFilter) bytes += normalFilter->getMemoryUsage();
        std::cerr << std::format("PrismRT Vulkan: vk_oidn filters for {}x{} ({}{}): {} MiB, {} tile(s)\n",
                                 wanted.width, wanted.height, color->getWeightsName(),
                                 prefilter ? ", prefiltered guides" : "", bytes >> 20, color->getTileCount());
    }
}

void VulkanDenoiser::Impl::pass(VkCommandBuffer commands, PassParams params)
{
    vkCmdBindPipeline(commands, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
    vkCmdPushConstants(commands, layout, VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(params), &params);
    vkCmdDispatch(commands, (params.count + 63) / 64, 1, 1);
}

template <typename Fill> void VulkanDenoiser::Impl::run(Key const& wanted, Fill&& fill)
{
    const auto start = std::chrono::steady_clock::now();
    ensureFilters(wanted);
    const auto filtered = std::chrono::steady_clock::now();
    const VkDeviceSize count = VkDeviceSize(wanted.width) * wanted.height, bytes = count * 16;
    reserve(images, bytes * kImageCount, Memory::Device);
    reserve(readback, bytes, Memory::Readback);
    const bool prefilter = albedoFilter != nullptr;
    VkCommandBuffer commands = begin();
    vkCmdResetQueryPool(commands, timestamps, 0, 2);
    vkCmdWriteTimestamp(commands, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, timestamps, 0);
    // Earlier submissions (the render's dispatches into the accumulation,
    // the last denoise's reads of these images) come first.
    Barrier(commands, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, VK_ACCESS_MEMORY_READ_BIT | VK_ACCESS_MEMORY_WRITE_BIT,
            VK_PIPELINE_STAGE_TRANSFER_BIT | VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT,
            VK_ACCESS_TRANSFER_READ_BIT | VK_ACCESS_TRANSFER_WRITE_BIT | VK_ACCESS_SHADER_READ_BIT |
                VK_ACCESS_SHADER_WRITE_BIT);
    // fill() leaves the colour and the guides in `images`, written by
    // transfers or compute shaders.
    try {
        fill(commands);
        Barrier(commands, VK_PIPELINE_STAGE_TRANSFER_BIT | VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT,
                VK_ACCESS_TRANSFER_WRITE_BIT | VK_ACCESS_SHADER_WRITE_BIT, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT,
                VK_ACCESS_SHADER_READ_BIT | VK_ACCESS_SHADER_WRITE_BIT);
        vkoidn::DenoiseInputs inputs;
        inputs.color = image(kColor);
        inputs.output = image(kOutput);
        if (wanted.albedo) inputs.albedo = image(prefilter ? kCleanAlbedo : kAlbedo);
        if (wanted.normal) inputs.normal = image(prefilter ? kCleanNormal : kNormal);
        if (prefilter) {
            vkoidn::DenoiseInputs albedo;
            albedo.color = image(kAlbedo);
            albedo.output = image(kCleanAlbedo);
            Check(albedoFilter->cmdDenoise(commands, albedo), "the albedo prefilter");
            if (normalFilter) {
                const uint32_t pixels = uint32_t(count);
                pass(commands, {image(kNormal).address, 0, image(kNormal).address, 0, 0, pixels, kNormalToUnit});
                ComputeBarrier(commands);
                vkoidn::DenoiseInputs normal;
                normal.color = image(kNormal);
                normal.output = image(kCleanNormal);
                Check(normalFilter->cmdDenoise(commands, normal), "the normal prefilter");
                ComputeBarrier(commands);
                pass(commands, {image(kCleanNormal).address, 0, image(kCleanNormal).address, 0, 0, pixels,
                                kNormalFromUnit});
            }
            ComputeBarrier(commands);
        }
        Check(color->cmdDenoise(commands, inputs), "the colour filter");
    } catch (...) {
        vkEndCommandBuffer(commands);
        vkFreeCommandBuffers(d.device, pool, 1, &commands);
        throw;
    }
    Barrier(commands, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_ACCESS_SHADER_WRITE_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT,
            VK_ACCESS_TRANSFER_READ_BIT);
    VkBufferCopy region{bytes * kOutput, 0, bytes};
    vkCmdCopyBuffer(commands, images.buffer, readback.buffer, 1, &region);
    Barrier(commands, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_ACCESS_TRANSFER_WRITE_BIT, VK_PIPELINE_STAGE_HOST_BIT,
            VK_ACCESS_HOST_READ_BIT);
    vkCmdWriteTimestamp(commands, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, timestamps, 1);
    submit(commands);
    if (gpu::GpuVerbose()) {
        uint64_t ticks[2] = {};
        double gpuMilliseconds = -1.0;
        if (vkGetQueryPoolResults(d.device, timestamps, 0, 2, sizeof(ticks), ticks, sizeof(uint64_t),
                                  VK_QUERY_RESULT_64_BIT) == VK_SUCCESS)
            gpuMilliseconds = double(ticks[1] - ticks[0]) * timestampPeriod * 1e-6;
        auto const end = std::chrono::steady_clock::now();
        std::cerr << std::format("PrismRT Vulkan: vk_oidn denoise {}x{}: filters {:.1f} ms, submission {:.1f} ms "
                                 "(GPU {:.2f} ms)\n", wanted.width, wanted.height,
                                 std::chrono::duration<double, std::milli>(filtered - start).count(),
                                 std::chrono::duration<double, std::milli>(end - filtered).count(), gpuMilliseconds);
    }
}

std::shared_ptr<VulkanDenoiser> VulkanDenoiser::Create(DenoiseDevice const& device, std::string* error)
{
    auto impl = std::make_unique<Impl>();
    std::string reason;
    if (!impl->initialize(device, &reason)) {
        if (error) *error = reason;
        return nullptr;
    }
    return std::shared_ptr<VulkanDenoiser>(new VulkanDenoiser(std::move(impl)));
}

VulkanDenoiser::VulkanDenoiser(std::unique_ptr<Impl> impl) : m_impl(std::move(impl)) {}

VulkanDenoiser::~VulkanDenoiser() { Shutdown(); }

void VulkanDenoiser::Shutdown()
{
    std::lock_guard lock(m_impl->mutex);
    m_impl->destroy();
    m_impl->shutdown = true;
}

std::string VulkanDenoiser::Name() const
{
    std::lock_guard lock(m_impl->mutex);
    if (m_impl->shutdown) return "OIDN CPU (the Vulkan device was released)";
    return std::format("vk_oidn {}.{}.{} Vulkan ({})", VK_OIDN_VERSION_MAJOR, VK_OIDN_VERSION_MINOR,
                       VK_OIDN_VERSION_PATCH,
                       m_impl->context->isCooperativeMatrixEnabled() ? "cooperative matrices"
                                                                     : "generic convolutions");
}

void VulkanDenoiser::Denoise(DenoiseRequest const& request)
{
    std::unique_lock lock(m_impl->mutex);
    if (m_impl->shutdown) {
        lock.unlock();
        auto cpu = SharedCpuDenoiser();
        if (!cpu) throw std::runtime_error("denoise: the Vulkan device was released and there is no CPU denoiser");
        cpu->Denoise(request);
        return;
    }
    Impl& impl = *m_impl;
    const size_t width = request.width, height = request.height;
    if (!width || !height || !request.color.pixels || !request.output || request.color.stride < 3 ||
        request.outputStride < 3 || (request.albedo.pixels && request.albedo.stride < 3) ||
        (request.normal.pixels && request.normal.stride < 3))
        throw std::runtime_error("denoise: empty or malformed images");
    Impl::Key wanted;
    wanted.width = request.width;
    wanted.height = request.height;
    wanted.settings = request.settings;
    // OIDN takes a normal only together with an albedo.
    wanted.albedo = request.albedo.pixels != nullptr;
    wanted.normal = wanted.albedo && request.normal.pixels != nullptr;
    const size_t count = width * height;
    const VkDeviceSize bytes = VkDeviceSize(count) * 16;
    impl.reserve(impl.upload, bytes * 3, Memory::Upload);
    auto* staging = static_cast<float*>(impl.upload.mapped);
    const HostImage sources[3] = {request.color, wanted.albedo ? request.albedo : HostImage{},
                                  wanted.normal ? request.normal : HostImage{}};
    tbb::parallel_for(tbb::blocked_range<size_t>(0, count, 16384), [&](tbb::blocked_range<size_t> const& range) {
        for (int k = 0; k < 3; ++k) {
            if (!sources[k].pixels) continue;
            float* out = staging + 4 * count * k;
            for (size_t p = range.begin(); p != range.end(); ++p) {
                const float* in = sources[k].pixels + p * sources[k].stride;
                out[4 * p] = in[0];
                out[4 * p + 1] = in[1];
                out[4 * p + 2] = in[2];
                out[4 * p + 3] = 1.0f;
            }
        }
    });
    impl.run(wanted, [&](VkCommandBuffer commands) {
        VkBufferCopy region{0, 0, bytes * (wanted.normal ? 3 : wanted.albedo ? 2 : 1)};
        vkCmdCopyBuffer(commands, impl.upload.buffer, impl.images.buffer, 1, &region);
    });
    auto const* denoised = static_cast<const float*>(impl.readback.mapped);
    tbb::parallel_for(tbb::blocked_range<size_t>(0, count, 16384), [&](tbb::blocked_range<size_t> const& range) {
        for (size_t p = range.begin(); p != range.end(); ++p)
            for (int c = 0; c < 3; ++c) request.output[p * request.outputStride + c] = denoised[4 * p + c];
    });
}

void VulkanDenoiser::DenoiseAccumulation(VkDeviceAddress accumulation, std::vector<int> const& samples,
                                         unsigned width, unsigned height, DenoiseSettings const& settings,
                                         std::vector<float>* output)
{
    std::lock_guard lock(m_impl->mutex);
    Impl& impl = *m_impl;
    if (impl.shutdown) throw std::runtime_error("denoise: the Vulkan device was released");
    const size_t count = size_t(width) * height;
    if (!count || samples.size() != count || !accumulation)
        throw std::runtime_error("denoise: the render has no accumulation to denoise");
    Impl::Key wanted;
    wanted.width = width;
    wanted.height = height;
    wanted.settings = settings;
    wanted.albedo = wanted.normal = true;
    impl.reserve(impl.scales, VkDeviceSize(count) * 4, Memory::Upload);
    auto* scales = static_cast<float*>(impl.scales.mapped);
    // The scale the host applies to the same sums (gpu_device.cpp).
    for (size_t p = 0; p < count; ++p) scales[p] = samples[p] > 0 ? 1.0f / float(samples[p]) : 0.0f;
    impl.run(wanted, [&](VkCommandBuffer commands) {
        PassParams params;
        params.source = accumulation;
        params.scales = impl.scales.address;
        params.color = impl.image(kColor).address;
        params.albedo = impl.image(kAlbedo).address;
        params.normal = impl.image(kNormal).address;
        params.count = uint32_t(count);
        params.mode = kResolve;
        impl.pass(commands, params);
    });
    output->resize(3 * count);
    auto const* denoised = static_cast<const float*>(impl.readback.mapped);
    for (size_t p = 0; p < count; ++p)
        for (int c = 0; c < 3; ++c) (*output)[3 * p + c] = denoised[4 * p + c];
}

