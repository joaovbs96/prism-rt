#!/usr/bin/env python3
"""Writes a C++ source embedding binary files, for data the build must carry
inside the libraries (the Vulkan denoiser's prefilter weights).

  embed_files.py OUTPUT FUNCTION FILE...

defines, in namespace prism::embedded,
  const void* FUNCTION(const char* name, size_t* size);
returning a file by its name without extension (null if absent). The data
are 256-byte aligned 64-bit words, which compile much faster than bytes.
"""
import os
import struct
import sys


def main():
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    output, function, files = sys.argv[1], sys.argv[2], sys.argv[3:]
    lines = ["// Generated by cmake/embed_files.py; do not edit.", "",
             "#include <cstddef>", "#include <cstdint>", "#include <cstring>", "",
             "namespace prism::embedded {", "", "namespace {", ""]
    entries = []
    for index, path in enumerate(files):
        with open(path, "rb") as f:
            data = f.read()
        padded = data + b"\0" * (-len(data) % 8)
        words = struct.unpack("<%dQ" % (len(padded) // 8), padded)
        lines.append("alignas(256) const uint64_t file%d[%d] = {" % (index, max(len(words), 1)))
        for start in range(0, len(words), 8):
            lines.append(",".join("0x%x" % w for w in words[start:start + 8]) + ",")
        if not words:
            lines.append("0")
        lines.append("};")
        lines.append("")
        entries.append((os.path.splitext(os.path.basename(path))[0], index, len(data)))
    lines.append("struct File { const char* name; const void* data; size_t size; };")
    lines.append("const File files[] = {")
    for name, index, size in entries:
        lines.append('    {"%s", file%d, %d},' % (name, index, size))
    lines.append("    {nullptr, nullptr, 0},")
    lines.append("};")
    lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("const void* %s(const char* name, size_t* size)" % function)
    lines.append("{")
    lines.append("    for (const File* f = files; f->name; ++f)")
    lines.append("        if (std::strcmp(f->name, name) == 0) {")
    lines.append("            if (size) *size = f->size;")
    lines.append("            return f->data;")
    lines.append("        }")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace prism::embedded")
    lines.append("")
    content = "\n".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    # Unchanged output keeps its time stamp (no recompilation).
    if os.path.exists(output):
        with open(output) as f:
            if f.read() == content:
                return 0
    with open(output, "w") as f:
        f.write(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
