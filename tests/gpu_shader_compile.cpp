// The GPU kernel compiles for a scene with an MDL material: to SPIR-V for the
// Vulkan device (also on macOS, where no driver can execute it) and to DXIL
// for the Metal device; plus the HLSL double-precision rewrite.
//   prism_gpu_shader_compile_test <scene.usda>
#include "../src/device/gpu/gpu_scene.h"
#include "../src/device/gpu/hlsl_compiler.h"
#include "../src/device/gpu/shader_sources.h"
#include "../src/device/gpu/hlsl_fp32_rewrite.h"
#include "scene_api_test_util.h"
#include "../src/scene.h"
#ifdef PRISM_HAS_VULKAN
#include "../src/device/vulkan/vulkan_device.h"
#include "../src/device/vulkan/vulkan_material_calls.h"
#endif

#include <cstdlib>
#include <format>
#include <iostream>

namespace {
int failures = 0;
void check(bool condition, std::string const& message)
{
    if (!condition) {
        std::cerr << "FAILED: " << message << '\n';
        ++failures;
    }
}
} // namespace

int main(int argc, char** argv)
{
    using namespace prism::device::gpu;
    // The fp32 rewrite: types and literal suffixes change, identifiers do not.
    std::string rewritten, error;
    check(RewriteHlslToFp32("double2 a = double2(1.0l, 2.5L); double3x3 m; "
                            "float b = mdl_read_argblock_as_double(4); // double comment\n",
                            &rewritten, &error) &&
          rewritten == "float2 a = float2(1.0f, 2.5f); float3x3 m; "
                       "float b = mdl_read_argblock_as_double(4); // double comment\n",
          "HLSL double rewrite: " + rewritten);
    // Generated by the MDL SDK HLSL backend for an FP64 material, and the
    // same code from the SDK's hlsl_disable_double option.
    check(RewriteHlslToFp32(
              "    double tmp1 = mdl_read_argblock_as_double(tmp0);\n"
              "    state.text_results[0].x = float(mdl_read_argblock_as_double(tmp0 + 8) + 0.375l + "
              "sin(tmp1 * double(tmp2.x)) * 0.375l * cos(tmp1 * double(tmp2.y)));\n",
              &rewritten, &error) &&
          rewritten ==
              "    float tmp1 = mdl_read_argblock_as_double(tmp0);\n"
              "    state.text_results[0].x = float(mdl_read_argblock_as_double(tmp0 + 8) + 0.375f + "
              "sin(tmp1 * float(tmp2.x)) * 0.375f * cos(tmp1 * float(tmp2.y)));\n",
          "rewrite matches hlsl_disable_double: " + rewritten);
    check(RewriteHlslToFp32("int x = 10L; uint y = 0x1fL;", &rewritten, &error) &&
          rewritten == "int x = 10L; uint y = 0x1fL;", "integer literal suffixes are kept: " + rewritten);

    if (argc < 2) {
        std::cerr << "usage: prism_gpu_shader_compile_test <scene.usda>\n";
        return 2;
    }
    {
        const prism::Renderer renderer(prism::test::TestRendererOptions());
        prism::Scene api = renderer.createScene();
        SceneManager& scene = prism::test::LoadUsd(api, argv[1]);
        GpuSceneData data = BuildGpuScene(scene);
        check(!data.mdlMaterials.empty(), "the scene has MDL materials");
        MdlShaderCode code = GenerateMdlShaderCode(data.mdlMaterials);
        check(code.success, "MDL code: " + code.error);
        for (auto const& m : code.materials) check(m.valid, "material: " + m.error);
#ifdef PRISM_HAS_VULKAN
        std::vector<uint32_t> spirv;
        check(prism::device::CompileVulkanKernel(code.code, &spirv, &error) && spirv.size() > 1000 &&
                  spirv[0] == 0x07230203u,
              "Vulkan kernel compiles to SPIR-V: " + error);
        // Its light AOV variant (PRISM_LIGHT_AOVS), and the raygen shader's.
        std::vector<uint32_t> aovSpirv;
        check(prism::device::CompileVulkanKernel(code.code, &aovSpirv, &error, 0, true) && aovSpirv.size() > 1000 &&
                  aovSpirv != spirv,
              "Vulkan light AOV kernel compiles to SPIR-V: " + error);
        {
            MdlShaderCode aovCode = code;
            aovCode.lightAovs = true;
            std::vector<std::string> aovSources;
            std::vector<char> raygen;
            check(prism::device::vulkan::MaterialCallSources(aovCode, true, &aovSources, &error) &&
                      aovSources[0].find("#define PRISM_LIGHT_AOVS 1") != std::string::npos &&
                      CompileHlsl(aovSources[0], HlslTarget::Spirv, ShaderCacheDirectory("test"), &raygen, &error,
                                  HlslStage{prism::device::vulkan::kMaterialCallProfile, ""}) &&
                      raygen.size() > 1000,
                  "light AOV raygen shader compiles to SPIR-V: " + error);
        }
        // The callable path: the raygen shader (with reordering) and each
        // program as one whole callable, or split into its sample and
        // evaluate parts (PRISM_VULKAN_SPLIT_PROGRAM_KIB=0 splits every one).
        for (const char* split : {"", "0"}) {
#ifdef _WIN32
            _putenv_s("PRISM_VULKAN_SPLIT_PROGRAM_KIB", split);
#else
            if (*split) setenv("PRISM_VULKAN_SPLIT_PROGRAM_KIB", split, 1);
            else unsetenv("PRISM_VULKAN_SPLIT_PROGRAM_KIB");
#endif
            namespace vk = prism::device::vulkan;
            const bool splitAll = *split != '\0';
            const std::string mode = splitAll ? " (split)" : "";
            std::vector<std::string> sources;
            check(vk::MaterialCallSources(code, true, &sources, &error) &&
                      sources.size() == (splitAll ? 2u : 1u) * code.programCount + 1u,
                  "callable sources" + mode + ": " + error);
            // Two slots per program: whole twice, or sample then evaluate.
            const std::vector<uint32_t> slots = vk::CallableSlots(sources);
            check(slots.size() == 2u * code.programCount, "two callable slots per program" + mode);
            for (size_t s = 0; s + 1 < slots.size(); s += 2) {
                const auto first = vk::CallablePart(sources[slots[s]]);
                const auto second = vk::CallablePart(sources[slots[s + 1]]);
                check(splitAll ? first == vk::MaterialCallPart::Sample && second == vk::MaterialCallPart::Evaluate &&
                                     slots[s + 1] == slots[s] + 1
                               : first == vk::MaterialCallPart::Whole && slots[s + 1] == slots[s],
                      std::format("program {}'s callable slots{}", s / 2, mode));
            }
            // Each callable keeps only its program's code, named without the program index.
            std::vector<std::string> whole;
            check(vk::MaterialCallSources(code, true, &whole, &error, false) && whole.size() == sources.size(),
                  "untrimmed callable sources" + mode + ": " + error);
            for (size_t s = 0; s < slots.size(); ++s) {
                const size_t i = slots[s];
                if (i >= whole.size()) continue;
                check(sources[i].size() <= whole[i].size(), std::format("callable {} is trimmed{}", i - 1, mode));
                check(sources[i].find(std::format("prism_p{}_", s / 2)) == std::string::npos &&
                          sources[i].find("prism_p_") != std::string::npos,
                      std::format("callable {} does not name its program index{}", i - 1, mode));
            }
            for (size_t i = 0; i < sources.size(); ++i) {
                std::vector<char> library;
                check(CompileHlsl(sources[i], HlslTarget::Spirv, ShaderCacheDirectory("test"), &library, &error,
                                  HlslStage{vk::kMaterialCallProfile, ""}) &&
                          library.size() > 1000,
                      (i == 0 ? std::string("raygen shader") : "callable " + std::to_string(i - 1)) + mode +
                          " compiles to SPIR-V: " + error);
            }
        }
#endif
        std::string source;
        std::vector<char> dxil;
        check(RewriteHlslToFp32(code.code, &rewritten, &error) &&
                  AssembleShader("gpu/kernel.hlsl", {"gpu/metal"}, rewritten, &source, &error) &&
                  CompileHlsl(source, HlslTarget::Dxil, ShaderCacheDirectory("test"), &dxil, &error) &&
                  dxil.size() > 1000,
              "Metal kernel compiles to DXIL: " + error);
        // The Metal device's light AOV variant: the same source after the define.
        std::vector<char> aovDxil;
        check(CompileHlsl("#define PRISM_LIGHT_AOVS 1\n" + source, HlslTarget::Dxil, ShaderCacheDirectory("test"),
                          &aovDxil, &error) && aovDxil.size() > 1000,
              "Metal light AOV kernel compiles to DXIL: " + error);
    }
    if (failures) return 1;
    std::cout << "GPU shader compile: all checks passed\n";
    return 0;
}
