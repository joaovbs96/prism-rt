"""Finds the native libraries before the extension modules load.

Python 3.8+ on Windows ignores PATH for the dependencies of extension
modules, so the directories holding prism.dll, prism_usd.dll and their
dependencies (Embree, oneTBB, MaterialX, OpenImageIO, OpenColorIO, OIDN, the
MDL SDK; USD for prismrt.usd) are added with os.add_dll_directory:

- PRISMRT_DLL_PATH (os.pathsep-separated), if set;
- the directories _build_config.py names: in a build tree, generated by
  CMake (absolute); in a wheel, written by tools/build_wheel.py (relative to
  the package: ``bin``);
- the package directory itself.

_build_config.py also names defaults for environment variables the renderer
reads (the MaterialX libraries, the MDL SDK root, DXC); variables already
set win. A wheel's config also lists DLLs to load by full path first (the
MDL SDK and its image plugin, which the renderer loads by name with
LoadLibrary, which does not search os.add_dll_directory's directories) and
the directories of its private USD (added by prismrt.usd only, so that
``import prismrt`` loads no USD).
"""

from __future__ import annotations

import os
import sys

_handles = []
DLL_DIRECTORIES: list[str] = []
PACKAGE = os.path.dirname(os.path.abspath(__file__))
#: True in a wheel (tools/build_wheel.py), False in a build tree.
PACKAGED = False


def package_path(path: str) -> str:
    """``path`` relative to the package directory (absolute paths unchanged)."""
    return os.path.normpath(os.path.join(PACKAGE, path))


def _config():
    try:
        from . import _build_config  # generated: CMake (build tree) or build_wheel.py (wheel)
    except ImportError:
        return None
    return _build_config


def add_directories(directories) -> None:
    """os.add_dll_directory for each directory not added yet, then the
    first-copy preload (below)."""
    seen = {os.path.normcase(d) for d in DLL_DIRECTORIES}
    for directory in directories:
        directory = package_path(directory)
        key = os.path.normcase(directory)
        if key in seen or not os.path.isdir(directory):
            continue
        seen.add(key)
        DLL_DIRECTORIES.append(directory)
        if sys.platform == "win32":
            _handles.append(os.add_dll_directory(directory))
    if sys.platform == "win32":
        _preload_first_copies()


def _configure() -> None:
    global PACKAGED
    directories = []
    extra = os.environ.get("PRISMRT_DLL_PATH", "")
    directories += [d for d in extra.split(os.pathsep) if d]
    config = _config()
    if config is not None:
        PACKAGED = bool(getattr(config, "PACKAGED", False))
        directories += list(config.DLL_DIRECTORIES)
        for name, value in config.ENVIRONMENT.items():
            if value and not os.environ.get(name):
                os.environ[name] = package_path(value)
    directories.append(PACKAGE)
    add_directories(directories)
    if config is not None and sys.platform == "win32":
        import ctypes
        for library in getattr(config, "PRELOAD", ()):
            path = package_path(library)
            if os.path.isfile(path):
                _preloaded.append(ctypes.WinDLL(path))


def _preload_first_copies() -> None:
    """Windows searches os.add_dll_directory directories in an unspecified
    order, so a DLL found in several of them (Embree ships an older tbb12.dll
    than oneTBB's) could come from any. Load the first directory's copy of
    each such DLL by its full path, as PATH order would."""
    import ctypes
    first: dict[str, str] = {}
    duplicated = []
    for directory in DLL_DIRECTORIES:
        try:
            names = os.listdir(directory)
        except OSError:
            continue
        for name in names:
            if not name.lower().endswith(".dll"):
                continue
            key = name.lower()
            if key not in first:
                first[key] = os.path.join(directory, name)
            elif key not in duplicated:
                duplicated.append(key)
    for key in duplicated:
        if key in _preloaded_names:
            continue
        try:
            _preloaded.append(ctypes.WinDLL(first[key]))
            _preloaded_names.add(key)
        except OSError:
            pass  # loaded later by name, as before


_preloaded = []
_preloaded_names: set[str] = set()
_configure()
